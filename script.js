function runTreeValidation() {
    const nodes = D.nodos || [], out = [];
    const orphan = nodes.filter(n => n.padre !== "P" && !nodes.some(p => p.codigo === n.padre));
    const levelJump = nodes.filter(n => Number(n.nivel) > 1 && !nodes.some(p => p.codigo === n.padre && Number(p.nivel) === Number(n.nivel) - 1));
    const dup = {}; nodes.forEach(n => { const k = n.tipo + "|" + n.enunciado.trim().toLowerCase(); dup[k] = (dup[k] || 0) + 1 }); const duplicates = nodes.filter(n => dup[n.tipo + "|" + n.enunciado.trim().toLowerCase()] > 1);
    const cross = nodes.filter(n => nodes.some(x => x !== n && x.enunciado.trim().toLowerCase() === n.enunciado.trim().toLowerCase() && x.tipo !== n.tipo));
    const noEvidence = nodes.filter(n => !n.evidencia || !n.lineaBase);
    const actions = nodes.filter(n => n.esAccion || /^(capacitar|crear|construir|implementar|diseñar|instalar|desarrollar|entregar|ejecutar|promover|fortalecer|realizar)\b/i.test(n.enunciado));
    const directCauses = nodes.filter(n => n.tipo === "causa" && Number(n.nivel) === 1), roots = nodes.filter(n => n.tipo === "causa" && Number(n.nivel) === 4);
    const tests = [
        [!orphan.length, "Dirección", "No hay nodos huérfanos; cada relación apunta a un padre válido.", orphan.map(n => n.codigo)],
        [!levelJump.length, "Nivel", "No hay saltos de nivel; cada nodo profundiza sobre el nivel inmediatamente superior.", levelJump.map(n => n.codigo)],
        [directCauses.length > 0 ? nodes.filter(n => n.tipo === "causa").every(n => n.nivel === 1 || nodes.some(p => p.codigo === n.padre)) : true, "Suficiencia / encadenamiento", "La estructura permite preguntar por qué hasta causas profundas; la suficiencia final requiere juicio del formulador.", []],
        [!cross.length && !duplicates.length, "No circularidad / duplicados", "No se detectan duplicados ni el mismo enunciado en ambos lados del árbol.", [...cross, ...duplicates].map(n => n.codigo)],
        [!noEvidence.length && !actions.length, "Evidencia y naturaleza del nodo", "Todos los nodos tienen evidencia y línea base y están formulados como estados, no acciones.", noEvidence.concat(actions).map(n => n.codigo)]
    ];
    const box = document.getElementById("treeValidation"); if (box) box.innerHTML = tests.map(([ok, t, m, bad]) => `<div class="vitem ${ok ? "ok" : "bad"}"><strong>${ok ? "✓" : "✕"} ${t}</strong><div class="small-note" style="margin-top:4px">${esc(m)}</div>${bad.length ? `<div class="small-note" style="margin-top:5px"><strong>Revisar:</strong> ${esc(bad.join(", "))}</div>` : ""}</div>`).join("");
}

